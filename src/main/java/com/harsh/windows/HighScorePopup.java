    private void SubmitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SubmitButtonActionPerformed
        // TODO add your handling code here:
        if(confirmer){
            switch(place){
                case 1:
                    level.setNameOne((String)NewInitials.getValue());
                    break;
                case 2:
                    level.setNameTwo((String)NewInitials.getValue());
                    break;
                case 3:
                    level.setNameThree((String)NewInitials.getValue());
            }
            level.createLevelFile(null);
            this.setVisible(false);
        }else{
            SubmitButton.setText("Confirm initials [" + (String)NewInitials.getValue() + "]?");
            confirmer = true;
        }
    }//GEN-LAST:event_SubmitButtonActionPerformed

