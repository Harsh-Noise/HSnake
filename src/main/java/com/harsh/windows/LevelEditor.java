    private void ExportButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ExportButtonActionPerformed
        // TODO add your handling code here:
        if(FileUploadWindow.getSelectedFile() == null){
            rootFrame.playDeath();
            FileUpload.setText("No music file!");
            return;
        }
        
        
        switch(getSelectedButtonText(buttonGroup1)){
            case "Liz":
                Liz = true;
                Tad = false;
                break;
            case "Tad":
                Liz = false;
                Tad = true;
                break;
            default:
                Liz = false;
                Tad = false;
        }
        
        int carRate = ((Integer)CarSpinner.getValue());
        if(carRate == 0){
            carRate = Integer.MAX_VALUE;
        }
                
        Level newLevel = new Level(
                TitleField.getText(), 
                (double)((int)LengthSpinner.getValue() * 1000), 
                ((Integer)BPMSpinner.getValue()), 
                ((Integer)UPBSpinner.getValue()), 
                ((Integer)SizeSpinner.getValue()), 
                ((Integer)BombSpinner.getValue()), 
                carRate, 
                ((Double)BurgerSpinner.getValue()), 
                ((Double)CherrySpinner.getValue()), 
                Liz, 
                Tad, 
                FileUploadWindow.getSelectedFile()
        );
        browser.addElement(newLevel);
        rootFrame.playClick();
    }//GEN-LAST:event_ExportButtonActionPerformed

